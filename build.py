#!/usr/bin/env python3
"""Build the trip site into dist/ from trip.json + src/ + photos/.

Edit trip.json (the only place trip data lives), then run:  python3 build.py
"""
import hashlib, json, shutil, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC, DIST, PHOTOS = ROOT / "src", ROOT / "docs", ROOT / "photos"
VENDOR = ROOT / "vendor" / "node_modules"

FONTS = [f"kanit-{s}-{w}-normal.woff2" for s in ("thai", "latin") for w in (500, 600, 700)] + \
        [f"noto-sans-thai-{s}-{w}-normal.woff2" for s in ("thai", "latin") for w in (400, 500, 600)]


def make_icons(out: Path):
    from PIL import Image, ImageDraw
    out.mkdir(parents=True, exist_ok=True)

    def draw(size, maskable=False):
        im = Image.new("RGB", (size, size), "#1b2a4a")
        d = ImageDraw.Draw(im)
        s = size / 512
        inset = 0.12 if maskable else 0.0
        k = 1 - inset * 2
        ox = oy = size * inset
        P = lambda x, y: (ox + x * s * k, oy + y * s * k)
        # moon glow
        d.ellipse([P(330, 70), P(430, 170)], fill="#ffb547")
        # Taipei 101: spire, cap, 8 stacked flared segments, base
        d.rectangle([P(252, 56), P(260, 112)], fill="#ffffff")
        d.polygon([P(226, 112), P(286, 112), P(278, 138), P(234, 138)], fill="#ffffff")
        y = 138
        for _ in range(7):
            d.polygon([P(214, y), P(298, y), P(286, y + 38), P(226, y + 38)], fill="#ffffff")
            y += 40
        d.rectangle([P(204, y), P(308, y + 34)], fill="#ffffff")
        # red ground band
        d.rectangle([P(0, 452), P(512, 512)], fill="#d6202f")
        return im

    draw(180).save(out / "apple-touch-icon.png")
    draw(192).save(out / "icon-192.png")
    draw(512).save(out / "icon-512.png")
    draw(512, maskable=True).save(out / "icon-maskable-512.png")


SW = r"""/* generated by build.py */
const VERSION = '__VERSION__';
const CORE = 'tp-core-' + VERSION;
const TILES = 'tp-tiles-v1';
const DATA = 'tp-data-v1';
const LEGACY = ['core-92024fe530', 'core-3901f30595', 'core-e28dcf9719', 'tiles-v1', 'data-v1'];
const PRECACHE = __PRECACHE__;
const TILE_LIMIT = 900;

self.addEventListener('install', e => {
  e.waitUntil((async () => {
    const c = await caches.open(CORE);
    await c.addAll(PRECACHE.map(u => new Request(u, {cache: 'reload'})));
    // First versions served mismatched files; replace them right away instead of waiting for a tap
    const keys = await caches.keys();
    if (keys.some(k => LEGACY.includes(k))) self.skipWaiting();
  })());
});
self.addEventListener('message', e => { if (e.data === 'skipWaiting') self.skipWaiting(); });
self.addEventListener('activate', e => {
  e.waitUntil((async () => {
    for (const k of await caches.keys())
      if ((k.startsWith('tp-core-') && k !== CORE) || LEGACY.includes(k)) await caches.delete(k);
    await self.clients.claim();
  })());
});
async function trimTiles(){
  const c = await caches.open(TILES); const keys = await c.keys();
  for (let i = 0; i < keys.length - TILE_LIMIT; i++) await c.delete(keys[i]);
}
self.addEventListener('fetch', e => {
  const req = e.request; if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.hostname === 'tile.openstreetmap.org') {
    // Keep only tiles the user actually viewed (no bulk prefetch, per OSM tile policy)
    e.respondWith(caches.open(TILES).then(async c => {
      const hit = await c.match(req); if (hit) return hit;
      const res = await fetch(req); if (res.ok) { c.put(req, res.clone()); trimTiles(); } return res;
    }));
    return;
  }
  if (/open-meteo\.com|er-api\.com/.test(url.hostname)) {
    e.respondWith(fetch(req).then(res => { const cp = res.clone(); caches.open(DATA).then(c => c.put(req, cp)); return res; })
      .catch(() => caches.open(DATA).then(c => c.match(req))));
    return;
  }
  if (url.origin === location.origin && url.pathname.startsWith(new URL('./', location).pathname)) {
    // Page and assets always come from this version's cache, so they never mix versions
    e.respondWith(caches.open(CORE).then(async c => {
      if (req.mode === 'navigate') return (await c.match('./index.html')) || fetch(req);
      return (await c.match(req, {ignoreSearch: true})) || fetch(req);
    }));
  }
});
"""


def main():
    trip = json.loads((ROOT / "trip.json").read_text(encoding="utf-8"))
    photos = json.loads((PHOTOS / "photos.json").read_text(encoding="utf-8")) if (PHOTOS / "photos.json").exists() else {}

    if DIST.exists():
        shutil.rmtree(DIST)
    (DIST / "fonts").mkdir(parents=True)
    (DIST / "lib").mkdir()
    (DIST / "img").mkdir()

    for f in FONTS:
        pkg = "kanit" if f.startswith("kanit") else "noto-sans-thai"
        shutil.copy(VENDOR / "@fontsource" / pkg / "files" / f, DIST / "fonts" / f)
    shutil.copy(VENDOR / "leaflet/dist/leaflet.js", DIST / "lib/leaflet.js")
    shutil.copy(VENDOR / "leaflet/dist/leaflet.css", DIST / "lib/leaflet.css")
    shutil.copy(SRC / "app.css", DIST / "app.css")
    shutil.copy(SRC / "app.js", DIST / "app.js")

    pub = {}
    for key, p in photos.items():
        for k in ("file", "full"):
            if p.get(k):
                shutil.copy(PHOTOS / p[k], DIST / "img" / p[k])
        pub[key] = {**p, "file": "img/" + p["file"], "full": "img/" + (p.get("full") or p["file"])}

    make_icons(DIST / "icons")

    manifest = {
        "name": trip["trip"]["name"], "short_name": trip["trip"]["name"], "lang": "th",
        "start_url": "./", "scope": "./", "display": "standalone",
        "background_color": "#0d1218", "theme_color": "#1b2a4a",
        "icons": [
            {"src": "icons/icon-192.png", "sizes": "192x192", "type": "image/png"},
            {"src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png"},
            {"src": "icons/icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
        ],
    }
    (DIST / "manifest.webmanifest").write_text(json.dumps(manifest, ensure_ascii=False, indent=1), encoding="utf-8")

    trip_json = json.dumps(trip, ensure_ascii=False).replace("</", "<\\/")
    photos_json = json.dumps(pub, ensure_ascii=False).replace("</", "<\\/")
    html = (SRC / "index.html").read_text(encoding="utf-8")
    html = html.replace("/*TRIP_JSON*/", trip_json).replace("/*PHOTOS_JSON*/", photos_json)
    html = html.replace("__TITLE__", trip["trip"]["name"])
    html = html.replace("__DESC__", f'แผนเที่ยว{trip["trip"]["city"]} {trip["trip"]["start"]} ถึง {trip["trip"]["end"]}')

    files = sorted(p for p in DIST.rglob("*") if p.is_file())
    h = hashlib.sha256(html.encode())
    for p in files:
        h.update(p.read_bytes())
    version = h.hexdigest()[:10]
    html = html.replace("__VERSION__", version)
    (DIST / "index.html").write_text(html, encoding="utf-8")

    rel = ["./index.html"] + [str(p.relative_to(DIST)).replace("\\", "/") for p in files]
    sw = SW.replace("__VERSION__", version).replace("__PRECACHE__", json.dumps(rel, indent=1))
    (DIST / "sw.js").write_text(sw, encoding="utf-8")
    (DIST / ".nojekyll").write_text("")

    total = sum(p.stat().st_size for p in DIST.rglob("*") if p.is_file())
    print(f"built dist/ version {version} · {len(rel)} precached files · {total/1e6:.1f} MB")


if __name__ == "__main__":
    sys.exit(main())
